@dataclass
class ActionEvalResult:
    tick: int
    agent: str
    action: str
    location: str
    hour: int
    location_consistent: bool   # action fits the location?
    time_consistent: bool       # action fits the time?
    condition: str


def check_location_consistency(action: str, location: str) -> bool:
    """Check if action is appropriate for the location."""
    loc_type = LOCATION_TYPE_MAP.get(location, "")
    if not loc_type:
        return True  # unknown location, give benefit of doubt
    appropriate = LOCATION_APPROPRIATE_ACTIONS.get(loc_type, set())
    action_lower = action.lower()
    return any(keyword in action_lower for keyword in appropriate)


def check_time_consistency(action: str, hour: int) -> bool:
    """Check if action is appropriate for the time of day."""
    action_lower = action.lower()
    for (h_start, h_end), keywords in TIME_APPROPRIATE.items():
        if h_start <= hour < h_end:
            # At least one time-appropriate keyword should match
            return any(k in action_lower for k in keywords)
    return True  # fallback


class ActionGroundingEvaluator:
    """
    Run simulation under different conditions, collect agent actions at each
    tick, evaluate location and time consistency.
    """

    def __init__(self, config: EvalConfig):
        self.config = config
        self.server = config.aura_server
        self.results: List[ActionEvalResult] = []

    def _api(self, method: str, endpoint: str,
             json_data: Optional[dict] = None) -> dict:
        url = f"{self.server}{endpoint}"
        try:
            if method == "GET":
                r = requests.get(url, timeout=30)
            else:
                r = requests.post(url, json=json_data or {}, timeout=60)
            return r.json()
        except Exception as e:
            return {"error": str(e)}

    def run(self, conditions: Optional[List[dict]] = None,
            num_steps: int = 34) -> Dict[str, Any]:
        """Run one full day under each condition, evaluate every action."""

        if conditions is None:
            conditions = [
                {"name": "AURA-Full", "probe_enabled": True, "probe_max_steps": 2},
                {"name": "AURA-NoProbe", "probe_enabled": False, "probe_max_steps": 0},
            ]

        all_results = []

        for cond in conditions:
            print(f"\n{'='*60}")
            print(f"Condition: {cond['name']}")
            print(f"{'='*60}")

            # Reset
            self._api("POST", "/api/reset")
            time.sleep(1)
            self._api("POST", "/api/probe",
                      {"enabled": cond["probe_enabled"],
                       "max_steps": cond["probe_max_steps"]})
            time.sleep(0.5)

            for tick in range(1, num_steps + 1):
                step_resp = self._api("POST", "/api/step")
                time.sleep(0.3)

                state = self._api("GET", "/api/state")
                if "error" in state:
                    continue

                hour = state.get("hour", 6)

                for agent_data in state.get("agents", []):
                    name = agent_data.get("name", "")
                    action = agent_data.get("action", "")
                    location = agent_data.get("location", "")

                    if not action or action.lower() == "sleeping":
                        continue

                    loc_ok = check_location_consistency(action, location)
                    time_ok = check_time_consistency(action, hour)

                    result = ActionEvalResult(
                        tick=tick,
                        agent=name,
                        action=action,
                        location=location,
                        hour=hour,
                        location_consistent=loc_ok,
                        time_consistent=time_ok,
                        condition=cond["name"],
                    )
                    all_results.append(result)

                loc_ok_count = sum(
                    1 for r in all_results
                    if r.tick == tick and r.condition == cond["name"]
                    and r.location_consistent)
                tick_total = sum(
                    1 for r in all_results
                    if r.tick == tick and r.condition == cond["name"])
                if tick_total:
                    print(f"  tick {tick:2d} | hour={hour:2d} | "
                          f"loc_ok={loc_ok_count}/{tick_total}")

        self.results = all_results
        return self._aggregate(all_results)

    def _aggregate(self, results: List[ActionEvalResult]) -> Dict[str, Any]:
        summary = {"total": len(results), "conditions": {}}

        by_cond: Dict[str, List[ActionEvalResult]] = {}
        for r in results:
            by_cond.setdefault(r.condition, []).append(r)

        for cond, rs in by_cond.items():
            loc_ok = sum(1 for r in rs if r.location_consistent)
            time_ok = sum(1 for r in rs if r.time_consistent)
            both_ok = sum(1 for r in rs
                          if r.location_consistent and r.time_consistent)
            total = len(rs)
            summary["conditions"][cond] = {
                "location_accuracy": loc_ok / total if total else 0,
                "time_accuracy": time_ok / total if total else 0,
                "overall_accuracy": both_ok / total if total else 0,
                "total_actions": total,
            }

            # Per agent
            by_agent: Dict[str, List[ActionEvalResult]] = {}
            for r in rs:
                by_agent.setdefault(r.agent, []).append(r)
            summary["conditions"][cond]["per_agent"] = {}
            for agent, ars in by_agent.items():
                a_loc = sum(1 for r in ars if r.location_consistent)
                a_time = sum(1 for r in ars if r.time_consistent)
                a_total = len(ars)
                summary["conditions"][cond]["per_agent"][agent] = {
                    "location_accuracy": a_loc / a_total if a_total else 0,
                    "time_accuracy": a_time / a_total if a_total else 0,
                    "total": a_total,
                }

        return summary

    def save_results(self, path: Optional[str] = None):
        if path is None:
            path = Path(self.config.results_dir) / "action_grounding.json"
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        output = {
            "summary": self._aggregate(self.results),
            "results": [asdict(r) for r in self.results],
        }
        with open(path, "w") as f:
            json.dump(output, f, indent=2, ensure_ascii=False, default=str)
        print(f"\nResults saved to {path}")

    def print_summary(self, summary: Dict[str, Any]):
        print(f"\n{'='*60}")
        print("ACTION GROUNDING EVALUATION RESULTS")
        print(f"{'='*60}")
        for cond, stats in summary["conditions"].items():
            print(f"\n  [{cond}] ({stats['total_actions']} actions)")
            print(f"    Location consistency: {stats['location_accuracy']*100:.1f}%")
            print(f"    Time consistency:     {stats['time_accuracy']*100:.1f}%")
            print(f"    Overall (both):       {stats['overall_accuracy']*100:.1f}%")
            for agent, astats in stats.get("per_agent", {}).items():
                print(f"      {agent:12s}: loc={astats['location_accuracy']*100:.0f}% "
                      f"time={astats['time_accuracy']*100:.0f}% "
                      f"(n={astats['total']})")

    def generate_latex_table(self, summary: Dict[str, Any]) -> str:
        conditions = list(summary["conditions"].keys())
        agents = set()
        for cond_data in summary["conditions"].values():
            agents.update(cond_data.get("per_agent", {}).keys())
        agents = sorted(agents)

        lines = [
            r"\begin{table}[t]",
            r"\centering",
            r"\caption{Action Grounding Consistency (\%). "
            r"Location (Loc) and Time consistency.}",
            r"\label{tab:action_grounding}",
            r"\begin{tabular}{l" + "cc" * len(conditions) + "}",
            r"\toprule",
        ]
        header = "Agent"
        for cond in conditions:
            header += f" & \\multicolumn{{2}}{{c}}{{{cond}}}"
        lines.append(header + r" \\")
        subheader = ""
        for _ in conditions:
            subheader += " & Loc & Time"
        lines.append(subheader + r" \\")
        lines.append(r"\midrule")

        for agent in agents:
            row = agent.split()[0]  # first name only
            for cond in conditions:
                astats = summary["conditions"][cond].get(
                    "per_agent", {}).get(agent, {})
                loc = astats.get("location_accuracy", 0) * 100
                tm = astats.get("time_accuracy", 0) * 100
                row += f" & {loc:.0f} & {tm:.0f}"
            lines.append(row + r" \\")

        lines.append(r"\midrule")
        row = r"\textbf{Overall}"
        for cond in conditions:
            loc = summary["conditions"][cond]["location_accuracy"] * 100
            tm = summary["conditions"][cond]["time_accuracy"] * 100
            row += f" & \\textbf{{{loc:.0f}}} & \\textbf{{{tm:.0f}}}"
        lines.append(row + r" \\")

        lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}"])
        return "\n".join(lines)


